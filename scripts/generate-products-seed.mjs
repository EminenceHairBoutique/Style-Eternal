/**
 * generate-products-seed.mjs
 * One-time generator: seeds the Supabase `products` table from the hardcoded
 * src/data/products.js catalog so the admin panel lists every product and its
 * inline price/stock editor works. The storefront keeps reading the rich data
 * file for content; a price/stock overlay (src/hooks/useProductOverlay.js)
 * pulls price/stock/is_active back from this table so admin edits show live.
 *
 * Run: node scripts/generate-products-seed.mjs
 * Output: supabase/migrations/<timestamp>_seed_products.sql
 *
 * Maps the rich product schema → the products table subset:
 *   name, slug, description, price, compare_at_price, stock, category,
 *   variants (sizes as [{label,stock}]), images (string[]), is_active=true.
 *   ON CONFLICT (slug) DO NOTHING — safe to re-run, never overwrites edits.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { products } from "../src/data/products.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");

const sqlEsc = (s) => String(s ?? "").replace(/'/g, "''");

function rowFor(p) {
  const compare = typeof p.comparePrice === "number" ? p.comparePrice : null;
  // Derive a sensible starting stock: use limited quantity when tracked,
  // otherwise a default. Admins adjust this inline afterwards.
  const stock = typeof p.limitedQty === "number" ? p.limitedQty : 100;
  const variants = Array.isArray(p.sizes) ? p.sizes.map((s) => ({ label: s, stock: null })) : [];
  const images = Array.isArray(p.images) ? p.images : [];
  return {
    name: p.displayName || p.name,
    slug: p.slug,
    description: p.description || "",
    price: typeof p.price === "number" ? p.price : 0,
    compare_at_price: compare,
    stock,
    category: p.category || null,
    variants,
    images,
    is_active: true,
  };
}

const rows = products.map(rowFor);

const lines = [];
lines.push("-- ============================================================================");
lines.push("-- Style Eternal — Seed products from src/data/products.js");
lines.push("-- Generated by scripts/generate-products-seed.mjs — do not edit by hand.");
lines.push("--");
lines.push("-- Populates the products table (commerce subset) so the admin panel lists");
lines.push("-- and inline-edits every product. ON CONFLICT (slug) DO NOTHING keeps it");
lines.push("-- idempotent and never overwrites prices/stock an admin has already changed.");
lines.push("-- The storefront overlays price/stock/is_active from this table by slug.");
lines.push("-- ============================================================================");
lines.push("");

for (const r of rows) {
  const compareSql = r.compare_at_price == null ? "NULL" : `${r.compare_at_price}`;
  const categorySql = r.category == null ? "NULL" : `'${sqlEsc(r.category)}'`;
  const variantsSql = `'${sqlEsc(JSON.stringify(r.variants))}'::jsonb`;
  const imagesSql = `'${sqlEsc(JSON.stringify(r.images))}'::jsonb`;
  lines.push("INSERT INTO public.products (name, slug, description, price, compare_at_price, stock, category, variants, images, is_active)");
  lines.push(
    `VALUES ('${sqlEsc(r.name)}', '${sqlEsc(r.slug)}', '${sqlEsc(r.description)}', ${r.price}, ${compareSql}, ${r.stock}, ${categorySql}, ${variantsSql}, ${imagesSql}, true)`
  );
  lines.push("ON CONFLICT (slug) DO NOTHING;");
  lines.push("");
}

const ts = "20260531080000";
const outDir = join(repoRoot, "supabase", "migrations");
mkdirSync(outDir, { recursive: true });
const outPath = join(outDir, `${ts}_seed_products.sql`);
writeFileSync(outPath, lines.join("\n"), "utf8");

console.log(`Wrote ${outPath}`);
console.log(`Products seeded: ${rows.length}`);
